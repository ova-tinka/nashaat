  if (minutesPerCompletionMatch) return `${formatUnit(minutesPerCompletionMatch[1], 'minute')} لكل إنجاز مؤهل`;
  const addedCreditMatch = new RegExp(`^\\+${minuteCount} min$`).exec(value);
  if (addedCreditMatch) return `+${formatUnit(addedCreditMatch[1], 'minute')}`;
  const rewardAddedMatch = new RegExp(`^${minuteCount} min of screen time added\\.$`).exec(value);
  if (rewardAddedMatch) return `تمت إضافة ${formatUnit(rewardAddedMatch[1], 'minute')} إلى وقت الشاشة`;
