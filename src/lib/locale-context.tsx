export function translateNode(node: ReactNode, language: AppLanguage = activeLanguage): ReactNode {
  if (typeof node === 'string') return translateText(node, language);
  if (typeof node === 'number' && language === 'ar') return new Intl.NumberFormat('ar-QA').format(node);
  if (Array.isArray(node)) return node.map((entry) => translateNode(entry, language));
  if (isValidElement<{ children?: ReactNode }>(node) && node.props.children !== undefined) {
    return cloneElement(node, undefined, translateNode(node.props.children, language));
  }
  return node;
}

type LocaleContextValue = {
  language: AppLanguage;
  locale: string;
  isRTL: boolean;
  restartRequired: boolean;
  setLanguage: (language: AppLanguage) => Promise<void>;
};
const LocaleContext = createContext<LocaleContextValue>({
  language: 'en', locale: 'en-GB', isRTL: false, restartRequired: false, setLanguage: async () => undefined,
});

function applyDocumentLocale(language: AppLanguage) {
  activeLanguage = language;
  if (Platform.OS === 'web' && typeof document !== 'undefined') {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  }
}

export function LocaleProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<AppLanguage>('en');
  const [restartRequired, setRestartRequired] = useState(false);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    let active = true;
    void AsyncStorage.getItem(languageKey).then((saved) => {
      if (!active) return;
      const next: AppLanguage = saved === 'ar' ? 'ar' : 'en';
      setLanguageState(next);
      applyDocumentLocale(next);
      if (Platform.OS !== 'web') {
        I18nManager.allowRTL(true);
        I18nManager.swapLeftAndRightInRTL(true);
        I18nManager.forceRTL(next === 'ar');
      }
      setReady(true);
    }).catch(() => {
      if (!active) return;
      setLanguageState('en');
      applyDocumentLocale('en');
      if (Platform.OS !== 'web') {
        I18nManager.allowRTL(true);
        I18nManager.swapLeftAndRightInRTL(true);
        I18nManager.forceRTL(false);
      }
      setReady(true);
    });
    return () => { active = false; };
  }, []);

  const setLanguage = useCallback(async (next: AppLanguage) => {
    const needsRestart = Platform.OS !== 'web' && I18nManager.isRTL !== (next === 'ar');
    await AsyncStorage.setItem(languageKey, next);
    setLanguageState(next);
    setRestartRequired(needsRestart);
    applyDocumentLocale(next);
    if (Platform.OS !== 'web') {
      I18nManager.allowRTL(true);
      I18nManager.swapLeftAndRightInRTL(true);
      I18nManager.forceRTL(next === 'ar');
    } else if (typeof window !== 'undefined') {
      window.location.reload();
    }
  }, []);

  const value = useMemo<LocaleContextValue>(() => ({
    language, locale: language === 'ar' ? 'ar-QA' : 'en-GB', isRTL: language === 'ar', restartRequired, setLanguage,
  }), [language, restartRequired, setLanguage]);
  return <LocaleContext.Provider value={value}>{ready ? children : null}</LocaleContext.Provider>;
}

export function useLocale() { return useContext(LocaleContext); }
