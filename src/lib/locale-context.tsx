  const availableMatch = new RegExp(`^${minuteCount} minutes? available$`).exec(value);
  if (availableMatch) return `المتاح ${formatUnit(availableMatch[1], 'minute')}`;
  const availableBalanceMatch = new RegExp(`^Available: ${minuteCount} minutes?$`).exec(value);
